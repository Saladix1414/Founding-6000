import assert from 'node:assert/strict';
import { simulateBatchClose, simulateInvestmentScenario, parseScenarioCosts, simulateReferenceSale, simulateCampaignBusinessYear, simulateHolderExit, simulateManagedReserveScenario } from '../../../src/components/landing/economySimulation.ts';

const full=simulateBatchClose();
assert.equal(full.sales,460_000_000_000n);
assert.equal(full.reserve,230_000_000_000n);
assert.equal(full.outsideReserve,230_000_000_000n);
assert.equal(full.operatingNet,null);
assert.equal(full.minting, 60_000_000_000n);
assert.equal(full.forWebsite, 170_000_000_000n);
const investment = simulateManagedReserveScenario(full.reserve, 400, 1);
assert.equal(investment.openingLiquid, 207_000_000_000n);
assert.equal(investment.openingInvested, 23_000_000_000n);
assert.equal(investment.netChange, 920_000_000n);
const business = simulateCampaignBusinessYear(5_000_000_000n, 400, 1);
assert.equal(business.openingReserve, full.reserve);
assert.equal(business.totalBusinessContribution, 9_000_000_000n);
assert.equal(business.closingReserve, 239_920_000_000n);
assert.equal(business.executionAuthorized, false);
assert.equal(simulateHolderExit("EPIC", 400, 1).modeledRedemption, 35_140_000n);
assert.equal(full.stages.reduce((n,s)=>n+s.quantity,0),6000);
assert.deepEqual(full.units.map(u=>u.reserve),[25_000_000_000n,70_000_000_000n,135_000_000_000n]);
assert.deepEqual(full.units.map(u=>u.perNft),[25_000_000n,35_000_000n,45_000_000n]);
const first=simulateBatchClose(1);
assert.equal(first.sales,50_000_000_000n); assert.equal(first.reserve,25_000_000_000n);
assert.equal(simulateBatchClose(2).reserve,95_000_000_000n);
for(let count=1;count<=3;count++) {
  const scenario=simulateBatchClose(count);
  assert.equal(scenario.reserve*2n,scenario.sales);
  assert.equal(scenario.units.reduce((n,u)=>n+u.reserve,0n),scenario.reserve);
  for (const stage of scenario.stages) assert.equal(stage.revenue,simulateReferenceSale(stage.tier).price*BigInt(stage.quantity));
}
assert.equal(simulateBatchClose(3,1000000000n).operatingNet,229_000_000_000n);
assert.ok(simulateBatchClose(3,999999000000n).operatingNet<0n);
assert.equal(parseScenarioCosts(''),null);
assert.equal(parseScenarioCosts('10,25'),10250000n);
assert.equal(parseScenarioCosts('0'),0n);
assert.equal(parseScenarioCosts('10.5'),10500000n);
for(const invalid of ['-1','1e3','NaN','Infinity','1.234','1,000.00','1000000000']) assert.throws(()=>parseScenarioCosts(invalid));
const flat=simulateInvestmentScenario(full.reserve,0,5);
assert.equal(flat.netChange,0n);
assert.equal(simulateInvestmentScenario(100000000n,1000,2).closingReserve,121000000n);
assert.equal(simulateInvestmentScenario(100000000n,-1000,2).closingReserve,81000000n);
assert.equal(simulateInvestmentScenario(full.reserve,-10000,1).closingReserve,0n);
for(const args of [[-1n,0,1],[1n,10001,1],[1n,0,0],[1n,0,6],[1n,NaN,1]]) assert.throws(()=>simulateInvestmentScenario(...args));
for(const count of [0,4,1.5,NaN]) assert.throws(()=>simulateBatchClose(count));
